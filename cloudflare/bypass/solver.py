import asyncio
import json
import sys
import time
from pathlib import Path
from playwright.async_api import async_playwright

# Fix Windows terminal encoding (PowerShell default is cp1252)
if sys.stdout.encoding != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# Paths
BASE_DIR        = Path(__file__).resolve().parent          # cloudflare/bypass/
CLOUDFLARE_DIR  = BASE_DIR.parent                          # cloudflare/
ROOT_DIR        = CLOUDFLARE_DIR.parent                    # Discord Bot/
CONFIG_PATH     = ROOT_DIR / "scraper" / "core" / "config.py"
COOKIES_PATH    = BASE_DIR / "cookies.json"

SEARCH_URL      = "https://www.upwork.com/nx/search/jobs/?q=python"
GRAPHQL_URL     = "https://www.upwork.com/api/graphql/v1"

def _write_config(headers: dict, cookies: list, user_agent: str):
    cookie_dict = {c["name"]: c["value"] for c in cookies}
    timestamp = time.strftime("%Y-%m-%d %H:%M:%S")

    config_content = f'''# ===========================================================================
# AUTO-GENERATED by cloudflare/bypass/solver.py
# Last refreshed: {timestamp}
# DO NOT edit manually - this file is overwritten on each token refresh.
# ===========================================================================

HEADERS = {{
    "authorization": {repr(headers.get("authorization", ""))},
    "user-agent": {repr(user_agent)},
    "accept": "*/*",
    "content-type": "application/json",
    "x-upwork-api-tenantid": {repr(headers.get("x-upwork-api-tenantid", ""))}
}}

COOKIES = {repr(cookie_dict)}
'''

    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        f.write(config_content)

    print(f"[OK] config.py updated -> {CONFIG_PATH}")
    print(f"     Authorization: {headers.get('authorization', 'NOT FOUND')[:60]}...")
    print(f"     Total cookies written: {len(cookie_dict)}")

async def _intercept_graphql(page):
    captured = {}
    captured_event = asyncio.Event()

    async def handle_request(request):
        if GRAPHQL_URL in request.url:
            all_headers = request.headers
            for key, value in all_headers.items():
                if key.lower() in {"authorization", "x-upwork-api-tenantid"}:
                    captured[key.lower()] = value
            if "authorization" in captured:
                captured_event.set()

    page.on("request", handle_request)

    print("[*] Opening Upwork public search page to solve Cloudflare and grab Visitor Token...")
    await page.goto(SEARCH_URL, wait_until="domcontentloaded", timeout=60000)

    # Trigger a 2nd page to force a GraphQL XHR payload if the first load didn't do it
    if not captured_event.is_set():
        print("[*] Simulating scroll & next page click to trigger GraphQL...")
        await page.evaluate("window.scrollBy(0, 1000)")
        await asyncio.sleep(2)
        await page.goto(SEARCH_URL + "&page=2", wait_until="domcontentloaded", timeout=60000)

    try:
        await asyncio.wait_for(captured_event.wait(), timeout=15)
        print("[OK] Authorization header captured!")
    except asyncio.TimeoutError:
        print("[!] Warning: Authorization header was NOT captured.")

    return captured

async def bootstrap():
    """
    Main solver function: Zero-Login Cloudflare Bypass.
    Opens a real Chromium browser, solves Cloudflare, harvests fresh tokens.
    """
    print("\n" + "=" * 60)
    print("  UPWORK AUTH SOLVER - Cloudflare Bypass")
    print("=" * 60)

    async with async_playwright() as p:
        browser = await p.chromium.launch(
            headless=False,
            slow_mo=50,
            args=[
                "--start-maximized",
                "--disable-blink-features=AutomationControlled",
            ]
        )

        context = await browser.new_context(
            viewport={"width": 1280, "height": 800},
            locale="en-US",
            timezone_id="America/New_York",
        )

        await context.add_init_script(
            "Object.defineProperty(navigator, 'webdriver', {get: () => undefined})"
        )

        page = await context.new_page()

        captured_headers = await _intercept_graphql(page)

        print("[*] Extracting cookies and User-Agent...")
        cookies = await context.cookies()
        user_agent = await page.evaluate("navigator.userAgent")

        # Save cookies to local cache
        with open(COOKIES_PATH, "w", encoding="utf-8") as f:
            json.dump(cookies, f, indent=2)
        print(f"[OK] {len(cookies)} cookies saved -> {COOKIES_PATH}")

        # Overwrite scraper/core/config.py with fresh tokens
        _write_config(captured_headers, cookies, user_agent)

        print("\n[OK] Cloudflare bypass complete. Closing browser...\n")
        await browser.close()

if __name__ == "__main__":
    asyncio.run(bootstrap())
